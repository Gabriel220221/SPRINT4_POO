-- Tabelas/sequences usadas pela API (adapte aos nomes da SUA Sprint 3 e ajuste as Entities).
CREATE SEQUENCE SEQ_TRECHO START WITH 1 INCREMENT BY 1;
CREATE SEQUENCE SEQ_EQUIPE START WITH 1 INCREMENT BY 1;
CREATE SEQUENCE SEQ_INTERVENCAO START WITH 1 INCREMENT BY 1;
CREATE SEQUENCE SEQ_RELATORIO START WITH 1 INCREMENT BY 1;
CREATE SEQUENCE SEQ_ITEM_RELATORIO START WITH 1 INCREMENT BY 1;

CREATE TABLE TRECHO_RODOVIA (
  ID_TRECHO NUMBER PRIMARY KEY,
  RODOVIA VARCHAR2(60) NOT NULL,
  KM_INICIAL NUMBER(8,2) NOT NULL,
  KM_FINAL NUMBER(8,2) NOT NULL,
  TIPO VARCHAR2(30) NOT NULL,
  NIVEL_VEGETACAO_CM NUMBER(8,2) NOT NULL CHECK (NIVEL_VEGETACAO_CM >= 0)
);
CREATE TABLE EQUIPE_MANUTENCAO (
  ID_EQUIPE NUMBER PRIMARY KEY,
  NOME VARCHAR2(80) NOT NULL,
  ESPECIALIDADE VARCHAR2(40) NOT NULL,
  QTD_MEMBROS NUMBER(3) NOT NULL,
  ATIVA NUMBER(1) DEFAULT 1 NOT NULL
);
CREATE TABLE INTERVENCAO (
  ID_INTERVENCAO NUMBER PRIMARY KEY,
  DESCRICAO VARCHAR2(200) NOT NULL,
  STATUS VARCHAR2(20) NOT NULL,
  DATA_PREVISTA DATE NOT NULL,
  ID_TRECHO NUMBER NOT NULL REFERENCES TRECHO_RODOVIA(ID_TRECHO),
  ID_EQUIPE NUMBER NOT NULL REFERENCES EQUIPE_MANUTENCAO(ID_EQUIPE)
);
CREATE TABLE RELATORIO_PRIORIDADE (
  ID_RELATORIO NUMBER PRIMARY KEY,
  DATA_GERACAO TIMESTAMP NOT NULL,
  TOTAL_TRECHOS NUMBER NOT NULL,
  QTD_URGENTE NUMBER NOT NULL,
  QTD_CRITICO NUMBER NOT NULL,
  QTD_ATENCAO NUMBER NOT NULL,
  QTD_NORMAL NUMBER NOT NULL
);
CREATE TABLE ITEM_RELATORIO (
  ID_ITEM NUMBER PRIMARY KEY,
  ID_RELATORIO NUMBER NOT NULL REFERENCES RELATORIO_PRIORIDADE(ID_RELATORIO),
  ID_TRECHO NUMBER NOT NULL,
  RODOVIA VARCHAR2(60) NOT NULL,
  NIVEL_VEGETACAO_CM NUMBER(8,2) NOT NULL,
  CLASSIFICACAO VARCHAR2(15) NOT NULL
);
